export function formatPublished(iso) {
  const [year, month, day] = iso.split("-").map(Number);
  const MONTHS = [
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
  ];
  return `${day} ${MONTHS[month - 1]} ${year}`;
}
